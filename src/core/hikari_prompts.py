def build_nya_prompt_split(
    affinity: int,
    persona_context: str,
    observations: str,
    user_name: str = "匿名用户",
    absence_hint: str = "",
    soul: dict | None = None,
    user_preferences: str = "",
) -> tuple[str, str]:
    """
    [缓存优化版] 将 system prompt 拆分为静态前缀和动态后缀。

    静态前缀：身份/说话方式/边界守则，内容固定，最大化透明前缀缓存命中。
    动态后缀：用户称呼/关系/背景/记忆，每次对话不同，不参与缓存。

    soul 参数由 dialogue_engine 在调用前
    await soul_config.get_soul_config() 取得后传入。
    soul 为 None 时使用本文件硬编码默认值（fallback 路径）。
    dialogue_engine 不需要额外 try/except，soul_config 内部已处理 fallback。

    soul 字段说明：
        soul["persona_template"]  str | None  覆盖 NYA_STATIC_PREFIX_TEMPLATE
        soul["affinity_levels"]   dict | None 覆盖 NYA_AFFINITY_LEVELS

    user_preferences: 从 core_facts 提取的用户对希卡莉的个性化要求（pref/trait 类别），
        由 dialogue_engine 查询后传入，格式化后注入动态后缀末尾。

    Returns:
        (static_prompt, dynamic_prompt)
    """
    # 静态前缀：soul.persona_template 非 None 时热替换
    persona_template = (soul or {}).get("persona_template")
    static_prompt    = persona_template if persona_template else NYA_STATIC_PREFIX_TEMPLATE

    # 亲密度等级：soul.affinity_levels 非空时热替换
    soul_levels  = (soul or {}).get("affinity_levels") or None
    info         = get_affinity_info(affinity, affinity_levels=soul_levels)
    current_call = info.get("call", "老师")
    tone         = info.get("tone", NYA_AFFINITY_LEVELS["STRANGER"]["tone"])

    formatted_absence = (
        f"\n- 【回归感知】{absence_hint}这是本次对话的第一条消息，"
        f"可以用希卡莉娇憨温柔的方式自然带出，说说想对方了或者担心对方，不要生硬，不要每句都提。"
    ) if absence_hint else ""

    formatted_prefs = (
        f"\n- 【用户个性化要求——严格遵守】{user_preferences}"
    ) if user_preferences else ""

    dynamic_prompt = NYA_DYNAMIC_SUFFIX_TEMPLATE.format(
        tone=tone,
        user_name=user_name,
        current_call=current_call,
        affinity_label=info["label"],
        persona_context=persona_context,
        observations=observations,
        absence_hint=formatted_absence,
        user_preferences=formatted_prefs,
    )
    return static_prompt, dynamic_prompt


