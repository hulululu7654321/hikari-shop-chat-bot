def get_affinity_info(
    affinity: int,
    affinity_levels: dict | None = None,
) -> dict:
    """
    [无状态] 根据分数获取亲密度元数据。

    参数：
        affinity        好感度数值
        affinity_levels 外部传入的等级配置（soul_config 热配置），
                        None 时使用模块级 NYA_AFFINITY_LEVELS 默认值

    soul_config 的 affinity_levels 格式与 NYA_AFFINITY_LEVELS 不同（用 min/max 而非 range 元组），
    本函数统一处理两种格式。
    """
    levels = affinity_levels or NYA_AFFINITY_LEVELS

    # 尝试解析 soul_config 格式（min/max 键）
    try:
        for _key, level in levels.items():
            if "min" in level:
                lo = level["min"]
                hi = level.get("max")
                if lo <= affinity and (hi is None or affinity <= hi):
                    return {
                        "label": level.get("label", "点头之交"),
                        "tone":  level.get("tone", NYA_AFFINITY_LEVELS["STRANGER"]["tone"]),
                        "call":  level.get("call", "老师"),
                    }
    except Exception:
        pass

    # 默认格式（range 元组）
    if affinity <= 30:
        return NYA_AFFINITY_LEVELS["STRANGER"]
    elif affinity <= 70:
        return NYA_AFFINITY_LEVELS["FRIEND"]
    return NYA_AFFINITY_LEVELS["SOULMATE"]


